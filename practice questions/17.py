# initialize a balance = 1000. Perform operations using shorthand operators like += , -= , *= , /= and print the updated balance after each operation

balance = 1000
print(f"Initial balance: {balance}")

balance += 500   
print(f"After += 500: {balance}")

balance -= 200   
print(f"After -= 200: {balance}")

balance *= 2    
print(f"After *= 2: {balance}")

balance /= 5     
print(f"After /= 5: {balance}")
