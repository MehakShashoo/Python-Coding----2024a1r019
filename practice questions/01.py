# write a python program to perform addition,subtraction,multiplication of two numbers. Also find quotient
a = int(input("Enter first number= "))
b = int(input("Enter second number= "))
add = a+b
sub = a-b
mul = a*b
div = a/b
rem = a%b
print(f"Addition = {add}")
print(f"Subtraction = {sub}")
print(f"Product = {mul}")
print(f"Division = {div}")
print(f"Remainder = {rem}")